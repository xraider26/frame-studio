const React=require('react');
const {createRoot}=require('react-dom/client');
const {StepDocument}=require(path.join(out,'step-document.js'));
test('switching project documents preserves each unsaved draft and its source revision',async()=>{
 const root=createRoot(document.getElementById('root'));
 const project={id:'one',revision:4,documents:{brief:{text:'Saved brief'},script:{text:'Saved script'}}};
 const mount=async(step,p=project)=>React.act(()=>root.render(React.createElement(StepDocument,{key:p.id+step,project:p,step,busy:false,save:async fn=>fn(),onState:()=>{}})));
 await mount('brief');
 await React.act(()=>{const node=document.querySelector('textarea');Object.getOwnPropertyDescriptor(window.HTMLTextAreaElement.prototype,'value').set.call(node,'My unsaved brief');node.dispatchEvent(new window.Event('input',{bubbles:true}));});
 await mount('script');
 assert.equal(document.querySelector('textarea').value,'Saved script');
 await mount('brief',{...project,revision:7});
 assert.equal(document.querySelector('textarea').value,'My unsaved brief');
 assert.match(document.body.textContent,/draft is preserved/i);
 await mount('brief',{...project,id:'two'});
 assert.equal(document.querySelector('textarea').value,'Saved brief');
 await React.act(()=>root.unmount());
});
test('image export exposes selected real images and invalidates a portable package on a new revision',async()=>{
 const {ImageDelivery}=require(path.join(out,'image-delivery.js'));
 const root=createRoot(document.getElementById('root'));
 const project={id:'image',name:'Portrait',revision:2,shots:[{id:'shot',title:'Portrait',image_asset:'selected'}],assets:[{id:'selected',url:'/media/selected.png',kind:'image',stale:false},{id:'old',url:'/media/old.png',kind:'image',stale:true}]};
 global.fetch=async(_url,options)=>{assert.equal(JSON.parse(options.body).operation,'export_handoff');return {ok:true,json:async()=>({download_url:'/bundle.zip',markdown:'Prompts'})};};
 await React.act(()=>root.render(React.createElement(ImageDelivery,{project})));
 assert.ok(document.querySelector('a[href="/media/selected.png"]'));
 assert.equal(document.querySelector('a[href="/media/old.png"]'),null);
 await React.act(()=>document.querySelector('button').click());
 assert.ok(document.querySelector('a[href="/bundle.zip"]'));
 await React.act(()=>root.render(React.createElement(ImageDelivery,{project:{...project,revision:3}})));
 assert.equal(document.querySelector('a[href="/bundle.zip"]'),null);
 await React.act(()=>root.unmount());
});
